BASE_URL = "https://api.deepseek.com"
MYT = timezone(timedelta(hours=8), "MYT")  # Malaysia time, UTC+8 (no daylight saving time)
DB_COLUMNS = ["record_id", "label", "processed_at"]


# ------------------------------------------------------------
# Utility functions
# ------------------------------------------------------------
def now_myt():
    return datetime.now(MYT)


def fmt_time(dt):
    return dt.strftime("%Y-%m-%d %H:%M:%S")


def fmt_duration(sec):
    h, rem = divmod(int(sec), 3600)
    m, s = divmod(rem, 60)
    if h:
        return f"{h} h {m} min {s} s"
    if m:
        return f"{m} min {s} s"
    return f"{sec:.1f} s"


def load_data(path):
    if not os.path.exists(path):
        raise SystemExit(f"Data file not found: {path}")
    ext = os.path.splitext(path)[1].lower()
    if ext == ".xlsx":
        df = pd.read_excel(path, dtype=str, keep_default_na=False)
    elif ext == ".csv":
        try:
            df = pd.read_csv(path, dtype=str, keep_default_na=False, encoding="utf-8-sig")
        except UnicodeDecodeError:
            df = pd.read_csv(path, dtype=str, keep_default_na=False, encoding="gbk")
    else:
        raise SystemExit(f"Unsupported file format: {ext} (only .csv / .xlsx)")
    return df.fillna("")


def build_requirement_text(row):
    cols = TEXT_COLUMNS or [c for c in row.index if c != ID_COLUMN]
    if not any(str(row[c]).strip() for c in cols):
        return ""
    if len(cols) == 1:
        return str(row[cols[0]]).strip()
    return "\n".join(f"{c}: {row[c]}" for c in cols).strip()


def build_system_prompt(task_prompt):
    """Shared context first, followed by TASK"""
    parts = []
    if COMMON_PROMPT.strip():
        parts.append(COMMON_PROMPT.strip())
    parts.append(task_prompt.strip())
    return "\n\n".join(parts)


def normalize_label(value):
    """Normalize label variants to FR / NFR; return None if unrecognized"""
    t = re.sub(r"[\W_]", "", str(value or "").lower())
    if t in ("fr", "functional", "functionalrequirement"):
        return "FR"
    if t in ("nfr", "nonfr", "nonfunctional", "nonfunctionalrequirement"):
        return "NFR"
    return None


def parse_json(text):
    """Parse a JSON response; return None on failure"""
    if not text:
        return None
    cleaned = re.sub(r"^```(?:json)?\s*|\s*```$", "", text.strip())
    try:
        data = json.loads(cleaned)
    except json.JSONDecodeError:
        return None
    return data if isinstance(data, dict) else None


def check_answer(parsed, label, record_id, required_keys):
    """Check the response against OUTPUT RULES; retry if invalid and mark INVALID when retries are exhausted"""
    warnings = []
    missing = [k for k in required_keys if k not in parsed]
    if missing:
        warnings.append(f"Missing fields {', '.join(missing)}")
    if "id" in parsed and str(parsed["id"]).strip() != record_id:
        warnings.append(f"id was changed (response was {parsed['id']!r})")

    for key in ("reason", "test_focus"):
        if key in required_keys and (not isinstance(parsed.get(key), str) or not parsed[key].strip()):
            warnings.append(f"{key} must be non-empty text")
    if isinstance(parsed.get("reason"), str) and len(parsed["reason"].split()) > 30:
        warnings.append("reason exceeds 30 words")
    return warnings


def save_json(path, data):
    """Write to a temporary file before replacing, preventing JSON corruption if interrupted midway"""
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    os.replace(tmp, path)


def call_model(client, model, system_prompt, user_content, thinking,
               temperature=None, max_tokens=None):
    kwargs = {
        "model": model,
        "messages": [
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": user_content},
        ],
        "response_format": {"type": "json_object"},
        "extra_body": {"thinking": {"type": "enabled" if thinking else "disabled"}},
    }
    if temperature is not None and not thinking:  # temperature is not supported in thinking mode
        kwargs["temperature"] = temperature
    if max_tokens is not None:
        kwargs["max_tokens"] = max_tokens

    resp = client.chat.completions.create(**kwargs)
    msg = resp.choices[0].message
    reasoning = getattr(msg, "reasoning_content", None)
    return (msg.content or "").strip(), reasoning


# ------------------------------------------------------------
# One classifier (A or B) processes one requirement
# ------------------------------------------------------------
def classify(client, cfg, user_content, record_id):
    """Return (label, JSON record, elapsed seconds, error message or None, format warning list)"""
    t = time.perf_counter()
    label, parsed, raw, reasoning, error = "INVALID", None, None, None, None
    try:
        system_prompt = build_system_prompt(cfg["prompt"])
        for attempt in range(MAX_RETRIES + 1):
            temp = cfg["temperature"]
            if attempt > 0 and temp is not None:
                temp = 0.7  # relax slightly on retries to avoid repeating the same invalid output
            raw, reasoning = call_model(
                client, cfg["model"], system_prompt, user_content, cfg["thinking"],
                temperature=temp, max_tokens=cfg["max_tokens"],
            )
            parsed = parse_json(raw)
            got = normalize_label(parsed.get("label")) if parsed else None
            if got and not check_answer(parsed, got, record_id, cfg["required_keys"]):
                label = got
                break
        if label == "INVALID":
            error = f"Response is empty, JSON or required fields are invalid (retried {MAX_RETRIES} times)"
    except APIStatusError as e:
        if e.status_code in (400, 401, 402, 403, 404, 422):
            raise RuntimeError(f"DeepSeek HTTP {e.status_code}: check the API key, balance, model, or request parameters.") from None
        label, error = "ERROR", f"DeepSeek HTTP {e.status_code}"
    except Exception as e:
        label, error = "ERROR", f"{type(e).__name__}: call failed; check the network and service status"
    sec = time.perf_counter() - t

    warnings = []
    entry = {"record_id": record_id, "label": label, "time": fmt_time(now_myt())}
    if error is None:
        entry["answer"] = parsed
        warnings = check_answer(parsed, label, record_id, cfg["required_keys"])
        if warnings:
            entry["warnings"] = warnings
    else:
        entry["answer"] = None
        entry["error"] = error
        if raw:
            entry["raw_output"] = raw  # Keep the raw response for inspection
    if SAVE_REASONING and reasoning:
        entry["reasoning"] = reasoning
    return label, entry, sec, error, warnings


# ------------------------------------------------------------
# SQLite (A and B use the same schema: IDs, FR/NFR labels, and timestamps)
# ------------------------------------------------------------
def open_db(path):
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    conn = sqlite3.connect(path)
    conn.execute("""
    CREATE TABLE IF NOT EXISTS results (
        record_id     TEXT,   -- ID
        label         TEXT,   -- FR / NFR (INVALID / ERROR on failure)
        processed_at  TEXT    -- processing time (Malaysia time)
    )""")
    cols = [r[1] for r in conn.execute("PRAGMA table_info(results)")]
    if cols != DB_COLUMNS:
        conn.close()
        raise SystemExit(f"{path} was created by an older script version; delete or rename it before running.")
    return conn


def finished_ids(run_files, texts):
    """Read prior run snapshots: IDs classified as FR/NFR by both A and B (possibly across different runs); changed requirement text does not count"""
    ok = {"A": set(), "B": set()}
    for run_file in run_files:
        with open(SCRIPT_DIR / run_file, encoding="utf-8") as f:
            run = json.load(f)
        if run.get("prompt_version", "v1") != PROMPT_VERSION:
            raise SystemExit(f"{run_file} is a prompt {run.get('prompt_version', 'v1')} run; "
                             f"cannot resume with prompt {PROMPT_VERSION}.")
        for row in run["rows"]:
            if texts.get(row["record_id"]) != row.get("requirement"):
                continue
            for name in ok:
                if row.get(name, {}).get("label") in ("FR", "NFR"):
                    ok[name].add(row["record_id"])
    return ok["A"] & ok["B"]


# ------------------------------------------------------------
# Main program
# ------------------------------------------------------------
def main(skip_runs=None):
    for name, text in (("COMMON_PROMPT", COMMON_PROMPT), ("PROMPT_A", PROMPT_A), ("PROMPT_B", PROMPT_B)):
        if "(fill in" in text or not text.strip():
            raise SystemExit(f"Please fill in {name} in the script before running.")

    load_dotenv(SCRIPT_DIR / ".env")
    api_key = os.environ.get("DEEPSEEK_API_KEY")
    if not api_key:
        raise SystemExit("DEEPSEEK_API_KEY not found; check the .env file.")


    start_dt = now_myt()
    t0 = time.perf_counter()
    stamp = start_dt.strftime("%Y%m%d-%H%M%S-%f")
    print(f"Start time (Malaysia): {fmt_time(start_dt)}")

    df = load_data(SCRIPT_DIR / DATA_FILE)
    total = len(df)
    print(f"Reading {DATA_FILE}; total {total} rows")

    if ID_COLUMN and ID_COLUMN not in df.columns:
        raise SystemExit(f"ID column {ID_COLUMN!r} not found. Available columns: {list(df.columns)}")
    input_cols = TEXT_COLUMNS or [c for c in df.columns if c != ID_COLUMN]
    missing_cols = [c for c in input_cols if c not in df.columns]
    if missing_cols:
        raise SystemExit(f"Columns not found: {missing_cols}. Available columns: {list(df.columns)}")
    if TEXT_COLUMNS is None and len(input_cols) > 1:
        raise SystemExit(
            f"Data has multiple columns {input_cols}. Specify the requirement text column in TEXT_COLUMNS, "
            "to avoid sending other columns (such as human annotations) to the model."
        )
    if df.empty or not input_cols:
        raise SystemExit("Data is empty or has no requirement text column.")
    if ID_COLUMN:
        ids = df[ID_COLUMN].astype(str)
        if ids.str.strip().eq("").any() or ids.duplicated().any():
            raise SystemExit("Requirement IDs must not be empty or duplicated; fix the data before running.")
    if not any(build_requirement_text(row) for _, row in df.iterrows()):
        raise SystemExit("All requirement text is empty.")
    print(f"ID column: {ID_COLUMN or '(row number)'} Columns sent to the model: {input_cols}\n")

    if skip_runs:
        if not ID_COLUMN:
            raise SystemExit("--skip-done requires an ID column (ID_COLUMN).")
        texts = {str(row[ID_COLUMN]): build_requirement_text(row) for _, row in df.iterrows()}
        done_ids = finished_ids(skip_runs, texts)
        df = df[~df[ID_COLUMN].astype(str).isin(done_ids)].reset_index(drop=True)
        total = len(df)
        print(f"Skipped {len(done_ids)} rows; processing {total} rows (including previously failed or unrun rows)\n")
        if df.empty:
            raise SystemExit("All requirements are already complete; nothing to run.")

    output_dir = SCRIPT_DIR / JSON_DIR
    os.makedirs(output_dir, exist_ok=True)
    classifiers = [
        {"name": "A", "model": MODEL_A, "thinking": A_THINKING, "temperature": A_TEMPERATURE,
         "max_tokens": A_MAX_TOKENS, "prompt": PROMPT_A, "db": A_DB_FILE,
         "required_keys": ["id", "label", "reason"]},
        {"name": "B", "model": MODEL_B, "thinking": B_THINKING, "temperature": B_TEMPERATURE,
         "max_tokens": B_MAX_TOKENS, "prompt": PROMPT_B, "db": B_DB_FILE,
         "required_keys": ["id", "test_focus", "label", "reason"]},
    ]
    for cfg in classifiers:
        cfg["json_path"] = os.path.join(output_dir, f"{cfg['name'].lower()}_{stamp}.json")
        cfg["records"] = []
        cfg["counts"] = {"FR": 0, "NFR": 0, "INVALID": 0, "ERROR": 0}
        cfg["warned"] = 0

    report = {
        "run_id": stamp, "started_at": start_dt.isoformat(), "status": "running",
        "models": {"A": MODEL_A, "B": MODEL_B},
        "prompt_version": PROMPT_VERSION, "data_file": DATA_FILE,
        "prompts": {"common": COMMON_PROMPT.strip(), "A": PROMPT_A.strip(), "B": PROMPT_B.strip()},
        "rows": [{"record_id": str(row[ID_COLUMN]) if ID_COLUMN else str(i),
                  "requirement": build_requirement_text(row)}
                 for i, (_, row) in enumerate(df.iterrows(), start=1)],
    }
    report_path = str(output_dir / f"run_{stamp}.json")
    save_json(report_path, report)

    def flush():
        for cfg in classifiers:
            save_json(cfg["json_path"], cfg["records"])
        save_json(report_path, report)

    def process_row(record_id, text):
        """Run A and B in worker threads; return results to the main thread for writing. Only the main thread accesses the database and JSON files."""
        user_content = f"id: {record_id}\nrequirement: {text}"
        return [classify(client, cfg, user_content, record_id) for cfg in classifiers]

    client = OpenAI(api_key=api_key, base_url=BASE_URL, timeout=120, max_retries=2)
    pool = ThreadPoolExecutor(max_workers=WORKERS)
    exit_code = 0
    try:
        for cfg in classifiers:
            cfg["conn"] = open_db(SCRIPT_DIR / cfg["db"])
        jobs = {}
        for i, (_, row) in enumerate(df.iterrows(), start=1):
            record_id = str(row[ID_COLUMN]) if ID_COLUMN else str(i)
            text = build_requirement_text(row)
            if not text:
                print(f"[{i}/{total}] #{record_id} Empty row; skipped")
                continue
            jobs[pool.submit(process_row, record_id, text)] = (i, record_id, text)
        print(f"Total {len(jobs)} rows to classify; {WORKERS} at a time\n")

        progress = {"done": 0, "last_save": time.perf_counter()}
        recorded = set()

        def record(fut, results):
            recorded.add(fut)
            progress["done"] += 1
            done = progress["done"]
            i, record_id, text = jobs[fut]
            parts, warnings = [], []

            for cfg, (label, entry, sec, error, fmt_warnings) in zip(classifiers, results):
                entry["elapsed_seconds"] = round(sec, 3)
                entry["requirement"] = text
                entry["model"] = cfg["model"]
                entry["run_id"] = stamp
                report["rows"][i - 1][cfg["name"]] = entry
                cfg["counts"][label] += 1

                cfg["conn"].execute(
                    "INSERT INTO results (record_id, label, processed_at) VALUES (?, ?, ?)",
                    (record_id, label, entry["time"]),
                )
                cfg["conn"].commit()  # Save each record so progress is not lost if interrupted
                cfg["records"].append(entry)

                parts.append(f"{cfg['name']}: {label} {sec:.1f}s")
                if error:
                    warnings.append(f"⚠ {cfg['name']} {error}")
                if fmt_warnings:
                    cfg["warned"] += 1
                    warnings.append(f"ℹ {cfg['name']} format warning: " + "; ".join(fmt_warnings))

            if time.perf_counter() - progress["last_save"] >= SAVE_INTERVAL:
                flush()
                progress["last_save"] = time.perf_counter()

            print(f"[{done}/{len(jobs)}] #{record_id} → " + " | ".join(parts))
            for w in warnings:
                print("   " + w)

        fatal = None
        for fut in as_completed(jobs):
            try:
                results = fut.result()
            except RuntimeError as e:
                fatal = e
                break
            record(fut, results)
        if fatal:
            # Fatal error: cancel tasks that have not started, wait for in-flight requests to finish, and collect successful results before stopping.
            # Cancelled futures do not wake as_completed, so shut down with wait=True and inspect them individually.
            print(f"\n{fatal} Waiting for in-flight requests to finish...")
            pool.shutdown(wait=True, cancel_futures=True)
            for fut in jobs:
                if fut not in recorded and fut.done() and not fut.cancelled() and fut.exception() is None:
                    record(fut, fut.result())
            raise fatal

        report["status"] = "completed (with failures)" if any(c["counts"]["ERROR"] or c["counts"]["INVALID"] for c in classifiers) else "completed"
    except RuntimeError as e:
        report["status"] = "stopped: " + str(e)
        print(f"\nRun stopped: {e}")
        exit_code = 1
    except KeyboardInterrupt:
        report["status"] = "interrupted manually"
        exit_code = 130
        print("\nInterrupted manually. All processed results have been saved.")

    finally:
        pool.shutdown(wait=False, cancel_futures=True)  # Cancel tasks that have not started; do not write results from in-flight tasks
        for cfg in classifiers:
            if "conn" in cfg:
                cfg["conn"].close()
        if report["status"] == "running":
            report["status"] = "aborted unexpectedly"
        report["ended_at"] = now_myt().isoformat()
        flush()
        try:
            sheet = export_excel(report, SCRIPT_DIR / EXCEL_FILE)
            print(f"\nExcel saved: {SCRIPT_DIR / EXCEL_FILE} (worksheet {sheet})")
        except Exception as exc:
            exit_code = exit_code or 1
            print(f"\nExcel export failed ({type(exc).__name__}); JSON/SQLite results were preserved.")
            print(f"Close the Excel file if it is open or check file permissions, then run --export-run {report_path} to export again.")
        end_dt = now_myt()
        duration = time.perf_counter() - t0

        print("\n" + "=" * 55)
        print(f"Start time: {fmt_time(start_dt)} (Malaysia time)")
        print(f"End time: {fmt_time(end_dt)} (Malaysia time)")
        print(f"Total runtime: {fmt_duration(duration)}")
        for cfg in classifiers:
            c = cfg["counts"]
            print(f"{cfg['name']}: FR {c['FR']} | NFR {c['NFR']} | "
                  f"Invalid {c['INVALID']} | Errors {c['ERROR']} | Format warnings {cfg['warned']}   → {cfg['db']}")
        for cfg in classifiers:
            if cfg["records"]:
                print(f"{cfg['name']} full responses: {cfg['json_path']}")
        print("=" * 55)
    if any(c["counts"]["ERROR"] or c["counts"]["INVALID"] for c in classifiers):
        exit_code = exit_code or 1
    return exit_code


