# ============================================================
# Basic settings (edit as needed)
# ============================================================
SCRIPT_DIR = Path(__file__).resolve().parent
DATA_FILE = "data/healthy_nation.csv"  # Data file path; supports .csv / .xlsx (generated by prepare_data.py)
A_DB_FILE = "results/db/a_results.db"  # A metadata (created if missing)
B_DB_FILE = "results/db/b_results.db"  # B metadata (created if missing)
EXCEL_FILE = "results/team_results.xlsx"  # Report for each run; can be changed to an absolute path in a shared team directory
JSON_DIR = "results/answers"  # Folder for complete responses (each run creates two JSON files, a_ and b_)

TEXT_COLUMNS = ["requirement"]           # Column containing requirement text, e.g. ["requirement"]; None = automatically used when the data has only one content column
ID_COLUMN = "id"              # ID column name, e.g. "id"; None = use row numbers

MODEL_A = "deepseek-flash"
MODEL_B = "deepseek-v4-pro"

# Thinking mode: more accurate, but slower and more expensive
A_THINKING = False
B_THINKING = True

# temperature is effective only when thinking mode is off; 0 = most stable results
A_TEMPERATURE = 0
B_TEMPERATURE = 0

# Maximum output length; None = use the DeepSeek default (responses include a reason sentence, so do not set this too low)
A_MAX_TOKENS = None
B_MAX_TOKENS = None

PROMPT_VERSION = "v1"         # Set to the version in prompts_v2.py when running with --prompts v2
MAX_RETRIES = 2               # Retries when the response is empty, JSON is malformed, or label is not FR/NFR
SAVE_REASONING = False        # Whether to save reasoning in JSON (available only in thinking mode; can be lengthy)
WORKERS = 8                   # Requirements to process concurrently; 1 = process sequentially
SAVE_INTERVAL = 10            # Maximum interval in seconds between JSON snapshot saves (each database record is saved immediately; snapshots are always saved at the end)

