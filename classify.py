"""
DeepSeek requirements classification script (FR / NFR)
- A: deepseek-flash + PROMPT_A (definition-based classification)
- B: deepseek-v4-pro + PROMPT_B (test-based classification)
- A and B classify each requirement independently without seeing each other's result
- Shared context (COMMON_PROMPT: definitions and boundary rules) appears before both TASK sections
- Storage:
    a_results.db / b_results.db → IDs, FR/NFR labels, and timestamps
    answers/a_timestamp.json / answers/b_timestamp.json → complete JSON responses
    team_results.xlsx → each run adds a timestamp-named worksheet
    answers/run_timestamp.json → run snapshots used to restore Excel exports
- Shows Malaysia local time and total runtime (A/B agreement is calculated by a separate statistics script)

Install dependencies:
    pip install openai python-dotenv pandas openpyxl filelock

Place the .env file in the same folder as the script:
    DEEPSEEK_API_KEY=sk-your_key
"""

